def as_markdown(level="###"):
    """Словарь в markdown для сопроводительной документации.

    Источник один и тот же, поэтому страница и PDF разойтись не могут.
    """
    out = []
    for title, items in GLOSSARY:
        out.append(f"{level} {title}\n")
        for term, meaning in items:
            out.append(f"**{term}.** {meaning}\n")
    return "\n".join(out)

