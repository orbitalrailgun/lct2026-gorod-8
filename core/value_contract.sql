-- СЕМАНТИЧЕСКИЙ КОНТРАКТ raw_value -> класс состояния (Москоллектор)
-- Вход: rv = raw_value, td = тип_датчика (может быть NULL для 1142 каналов вне справочника)
-- Выход: класс из {НОРМА, СРАБОТКА, ОТКАЗ, ОТКЛЮЧЕНО, НЕОПРЕДЕЛЕНО, ТЕЛЕМЕТРИЯ_ЧИСЛО, МУСОР}
CASE
  /* ---- 1. ЧИСЛА (газ / температура / ИБП) ---- */
  WHEN TRY_CAST(replace(rv,',','.') AS DOUBLE) IS NOT NULL THEN
    CASE
      WHEN td='Газовый датчик' THEN
        CASE WHEN TRY_CAST(rv AS DOUBLE) IN (327.68, 10.23, -10.23) THEN 'МУСОР'      -- переполнение int16 / предел АЦП 1023
             WHEN TRY_CAST(rv AS DOUBLE) < 0 THEN 'МУСОР'                              -- только 2020-2021, отрицательный % НКПР
             ELSE 'ТЕЛЕМЕТРИЯ_ЧИСЛО' END
      WHEN td='Датчик температуры' THEN
        CASE WHEN TRY_CAST(rv AS DOUBLE) = -127 THEN 'МУСОР'                           -- обрыв 1-Wire (DS18B20)
             WHEN TRY_CAST(rv AS DOUBLE) <= -40 OR TRY_CAST(rv AS DOUBLE) >= 60 THEN 'МУСОР'  -- -3276, 999, 113..128
             ELSE 'ТЕЛЕМЕТРИЯ_ЧИСЛО' END
      WHEN td='ИБП' THEN 'ТЕЛЕМЕТРИЯ_ЧИСЛО'                                            -- малые целые 3..11, код/счётчик
      WHEN td='(НЕТ)' THEN                                                              -- 1142 канала вне справочника: тип выводим из формы значения
        CASE WHEN TRY_CAST(rv AS DOUBLE) = -127 THEN 'МУСОР'
             WHEN TRY_CAST(rv AS DOUBLE) < 0 THEN 'МУСОР'
             WHEN TRY_CAST(rv AS DOUBLE) >= 60 THEN 'МУСОР'
             ELSE 'ТЕЛЕМЕТРИЯ_ЧИСЛО' END
      ELSE 'МУСОР'                                                                      -- 15 событий числа на дискретных каналах
    END
  /* ---- 2. ДАТА-ВРЕМЯ В ПОЛЕ ЗНАЧЕНИЯ (только 'Состояние охраны', 51 канал) ---- */
  WHEN regexp_matches(rv,'^\d{2}\.\d{2}\.\d{4} \d{2}:\d{2}:\d{2}$') THEN 'МУСОР'
  /* ---- 3. ОТКЛЮЧЕНО ---- */
  WHEN rv='Отключено устройство' THEN 'ОТКЛЮЧЕНО'
  WHEN rv='Выключен' AND td NOT IN ('Переключатель','Состояние вентилятора','Состояние насоса') THEN 'ОТКЛЮЧЕНО'
  WHEN rv='Снято с охраны' THEN 'ОТКЛЮЧЕНО'
  /* ---- 4. НЕОПРЕДЕЛЕНО ---- */
  WHEN rv='Неопределен' THEN 'НЕОПРЕДЕЛЕНО'
  /* ---- 5. ОТКАЗ ---- */
  WHEN rv IN ('Неисправен','Батарея неисправна','Батарея разряжена',
              'Много неисправных устройств','Не определено') THEN 'ОТКАЗ'
  WHEN rv='Затоплен' THEN 'ОТКАЗ'                                                       -- бит слова неисправности насоса, НЕ вода
  WHEN rv='Обесточен' AND td IN ('Состояние вентилятора','Состояние насоса') THEN 'ОТКАЗ'
  /* ---- 6. СРАБОТКА ---- */
  WHEN rv IN ('Обнаружен дым','Обнаружен газ','Обнаружено движение','Не замкнут',
              'Рычаг сдернут','Температура ниже 3ºC','Температура выше 40ºC',
              'Работают все насосы в АНС','Вызов','Разговор','Питание от батарей') THEN 'СРАБОТКА'
  WHEN rv='Обесточен' THEN 'СРАБОТКА'                                                   -- 'Состояние фазы' и пр.: потеря питания
  WHEN rv='Включен' AND td IN ('Переключатель','Состояние вентилятора','Состояние насоса') THEN 'СРАБОТКА'  -- пуск механизма
  /* ---- 7. НОРМА ---- */
  WHEN rv IN ('Норма','Дыма нет','Движения нет','В норме от +3 до +40','Есть питание',
              'Питание от сети','Устройства на объекте исправны','Рычаг норма','На охране') THEN 'НОРМА'
  WHEN rv='Выключен' THEN 'НОРМА'                                                       -- останов исполнительного механизма
  WHEN rv='Включен' THEN 'НОРМА'                                                        -- 'Состояние фазы': 866 событий 2019
  ELSE 'НЕПОКРЫТО'
END

