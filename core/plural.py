"""Согласование существительных с числительными.

Карточка вердикта пишется для человека, и «1 сообщений о неисправности»
в ней выглядит ровно так, как выглядит машинный текст, которому не доверяют.
В текущем наборе вердиктов таких мест было 53: 33 раза «1 сообщений»,
18 раз «в N раз выше» вместо «раза», дважды «1 суток назад».

Правило русского языка, записанное один раз:

* оканчивается на 1, кроме 11              → единственное число («1 сутки»)
* оканчивается на 2, 3, 4, кроме 12-14     → форма родительного единственного
                                             («2 сообщения», «3 раза»)
* всё остальное, включая 11-14             → родительный множественного
                                             («5 сообщений», «11 раз»)

Формы задаются там же, где пишется фраза, — в шаблоне. Так автор текста
видит все три варианта рядом и не может забыть про один из них:

    "канал выходил на связь {v:.0f} {сутки|суток|суток} из 7"
"""

import re

# Группа форм внутри шаблона: ровно три варианта через вертикальную черту.
# Обычные поля формата ({v:.0f}, {base}) под шаблон не подходят — в них нет
# вертикальной черты, поэтому подстановка их не трогает.
GROUP = re.compile(r"\{([^{}|]+\|[^{}|]+\|[^{}|]+)\}")


def form(n, one, few, many):
    """Нужная форма существительного для числа n."""
    try:
        n = abs(int(round(float(n))))
    except (TypeError, ValueError):
        return many
    if n % 100 in (11, 12, 13, 14):
        return many
    tail = n % 10
    if tail == 1:
        return one
    if tail in (2, 3, 4):
        return few
    return many


def count(n, one, few, many):
    """Число вместе с согласованной формой: «3 сообщения»."""
    return f"{n:.0f} {form(n, one, few, many)}"


def apply(template, n):
    """Подстановка форм вида {сутки|суток|суток} по числу n."""
    return GROUP.sub(lambda m: form(n, *m.group(1).split("|")), template)
